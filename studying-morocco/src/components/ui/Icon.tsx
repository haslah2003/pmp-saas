import {
  Award,
  BadgeCheck,
  Baby,
  BookOpen,
  Briefcase,
  Building2,
  Bus,
  Calculator,
  Clock,
  Compass,
  Cpu,
  FileCheck,
  Globe,
  GraduationCap,
  HeartPulse,
  House,
  Landmark,
  Languages,
  Leaf,
  MapPin,
  MessageCircle,
  MoonStar,
  Palette,
  Plane,
  Scale,
  ShieldCheck,
  Sparkles,
  Stethoscope,
  Sun,
  Users,
  Wallet,
  type LucideIcon,
} from 'lucide-react'

import type { IconKey } from '@/lib/options'

const icons: Record<IconKey, LucideIcon> = {
  'graduation-cap': GraduationCap,
  building: Building2,
  home: House,
  plane: Plane,
  bus: Bus,
  'book-open': BookOpen,
  languages: Languages,
  'badge-check': BadgeCheck,
  'shield-check': ShieldCheck,
  'heart-pulse': HeartPulse,
  users: Users,
  briefcase: Briefcase,
  scale: Scale,
  stethoscope: Stethoscope,
  cpu: Cpu,
  landmark: Landmark,
  calculator: Calculator,
  globe: Globe,
  wallet: Wallet,
  sun: Sun,
  'map-pin': MapPin,
  sparkles: Sparkles,
  clock: Clock,
  'message-circle': MessageCircle,
  'file-check': FileCheck,
  'moon-star': MoonStar,
  palette: Palette,
  leaf: Leaf,
  compass: Compass,
  baby: Baby,
}

export function Icon({ name, className, strokeWidth = 1.75 }: { name?: string | null; className?: string; strokeWidth?: number }) {
  const Component = (name && icons[name as IconKey]) || Award
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden="true" />
}
